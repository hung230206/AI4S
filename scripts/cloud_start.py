"""Start the single-origin cloud demo; never falls back to a local database."""
import argparse
import json
import os
from pathlib import Path
import shutil
import signal
import socket
import subprocess
import sys
import threading
import time
from urllib.parse import urlsplit
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
WIN = os.name == "nt"
FLAGS = {"creationflags": subprocess.CREATE_NO_WINDOW} if WIN else {}


def prepare_environment(source, allow_loopback_http=False):
    env = dict(source)
    database = env.get("DATABASE_URL", "")
    if database.startswith("postgres://"):
        database = "postgresql+psycopg://" + database[len("postgres://"):]
    elif database.startswith("postgresql://"):
        database = "postgresql+psycopg://" + database[len("postgresql://"):]
    if not database.startswith("postgresql+psycopg://"):
        raise ValueError("Set a cloud DATABASE_URL using PostgreSQL; no local database fallback is allowed.")
    env["DATABASE_URL"] = database
    origin = env.get("PUBLIC_APP_URL") or env.get("RENDER_EXTERNAL_URL", "")
    parsed = urlsplit(origin)
    loopback = allow_loopback_http and parsed.hostname in {"localhost", "127.0.0.1", "::1"} and parsed.scheme == "http"
    if (parsed.scheme != "https" and not loopback) or not parsed.hostname or parsed.username or parsed.password or parsed.path not in ("", "/") or parsed.query or parsed.fragment:
        raise ValueError("Set PUBLIC_APP_URL or RENDER_EXTERNAL_URL to the exact HTTPS origin.")
    env["FRONTEND_ORIGIN"] = origin.rstrip("/")
    env["FRONTEND_EXTRA_ORIGINS"] = ""
    env["COOKIE_SECURE"] = "false" if loopback else "true"
    for key, expected in {"DEMO_MODE": "true", "ALLOW_REAL_PAYMENTS": "false", "PAYMENT_PROVIDER": "mock", "AIRWALLEX_ENABLED": "false"}.items():
        if env.get(key, expected).lower() != expected:
            raise ValueError("Cloud demo requires sandbox-only configuration.")
        env[key] = expected
    for key in ("APP_SESSION_SECRET", "MOCK_WEBHOOK_SECRET", "DEMO_OPERATOR_CODE"):
        if len(env.get(key, "")) < 16 or env[key].startswith("REPLACE_"):
            raise ValueError("Cloud session/provider/operator secrets must be generated by the hosting platform.")
    port = int(env.get("PORT", "10000"))
    api_port = int(env.get("INTERNAL_API_PORT", "8000"))
    if not 1 <= port <= 65535 or not 1 <= api_port <= 65535 or port == api_port:
        raise ValueError("Public and API ports must be valid and distinct.")
    if api_port != 8000 and not loopback:
        raise ValueError("The production image proxy expects internal API port 8000.")
    env["PORT"] = str(port)
    env["INTERNAL_API_PORT"] = str(api_port)
    env["HOSTNAME"] = "127.0.0.1" if loopback else "0.0.0.0"
    env["NODE_ENV"] = "production"
    env.setdefault("OCR_MAX_WORKERS", "1")
    env.setdefault("PROVIDER_WORKER_ENABLED", "true")
    return env


def assert_free(port):
    with socket.socket() as probe:
        if probe.connect_ex(("127.0.0.1", port)) == 0:
            raise ValueError("A requested port is already in use; no existing process was stopped.")


def stop_children(children):
    for child in reversed(children):
        if child.poll() is None:
            if WIN:
                subprocess.run(["taskkill.exe", "/PID", str(child.pid), "/T", "/F"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, **FLAGS)
            else:
                child.terminate()
    for child in children:
        try:
            child.wait(timeout=8)
        except subprocess.TimeoutExpired:
            child.kill()
            child.wait()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Validate hosting settings without opening a connection or printing secrets")
    parser.add_argument("--allow-loopback-http", action="store_true", help="Local smoke test only; HTTP must use an exact loopback origin")
    args = parser.parse_args()
    children = []
    stop = threading.Event()
    for sig in (signal.SIGINT, signal.SIGTERM):
        signal.signal(sig, lambda *_: stop.set())
    try:
        env = prepare_environment(os.environ, args.allow_loopback_http)
        if args.check:
            print("Cloud settings valid: explicit PostgreSQL, exact origin, secure sandbox configuration. No connections opened.")
            return 0
        node = shutil.which("node")
        server = Path(env.get("CLOUD_WEB_SERVER", str(ROOT / "frontend/server.js")))
        if not node or not server.is_file():
            raise ValueError("Build the standalone frontend before cloud startup.")
        api_port = int(env["INTERNAL_API_PORT"])
        assert_free(api_port)
        assert_free(int(env["PORT"]))
        for command in ([sys.executable, "-m", "alembic", "upgrade", "head"], [sys.executable, "-m", "app.seed"]):
            subprocess.run(command, cwd=ROOT / "backend", env=env, check=True, **FLAGS)
            if stop.is_set():
                return 0
        children.append(subprocess.Popen([sys.executable, "-m", "uvicorn", "app.main:app", "--host", "127.0.0.1", "--port", str(api_port), "--workers", "1"], cwd=ROOT / "backend", env=env, **FLAGS))
        deadline = time.monotonic() + 60
        ready = False
        while not stop.is_set() and time.monotonic() < deadline and children[0].poll() is None:
            try:
                with urlopen(f"http://127.0.0.1:{api_port}/api/v1/health", timeout=2) as response:
                    health = json.load(response)
                ready = health.get("status") == "ok" and health.get("allow_real_payments") is False
                if ready:
                    break
            except (OSError, ValueError):
                pass
            stop.wait(.4)
        if stop.is_set():
            return 0
        if not ready:
            raise ValueError("API/database readiness failed; public frontend was not started.")
        children.append(subprocess.Popen([node, str(server)], cwd=server.parent, env=env, **FLAGS))
        print("Cloud demo started. API is loopback-only; use the hosting HTTPS URL /test-lab.", flush=True)
        while not stop.wait(.4):
            if any(child.poll() is not None for child in children):
                raise ValueError("A cloud service exited; remaining owned services are stopping.")
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError) as exc:
        # Never print source environment, database URLs or exception details containing credentials.
        print("Cloud startup failed: " + type(exc).__name__ + ". Check required settings/build and preceding service logs.", file=sys.stderr, flush=True)
        return 1
    finally:
        stop_children(children)


if __name__ == "__main__":
    raise SystemExit(main())

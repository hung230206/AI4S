// Server output and the first client render both use Vietnamese. Activate saved
// preferences only after hydration, so stored languages cannot corrupt hydration.
let browserReady = false;
export function activateLocale() {browserReady = true; window.dispatchEvent(new Event("demo:preferences"));}
export function setLocale(locale: Locale) {
  writePreference("baoan.lang", locale);
  document.documentElement.lang = locale === "zh" ? "zh-CN" : locale;
}
export function getLocale(): Locale {
  if (!browserReady) return "vi";
  const value = preference("baoan.lang", "vi");
  return value === "en" || value === "zh" ? value : "vi";
}
export function localeTag() {return {vi: "vi-VN", en: "en-GB", zh: "zh-CN"}[getLocale()];}
export function tr(source: string): string {
  const locale = getLocale();
  if (locale === "vi") return source;
  const key = source.trim().replace(/\s+/g, " ");
  const translated = phrases[key]?.[locale];
  if (!translated) return source;
  return source.match(/^\s*/)?.[0] + translated + source.match(/\s*$/)?.[0];
}
export function t(key: string, params?: Record<string, string>): string {
  const locale = getLocale();
  let text = messages[locale]?.[key] ?? messages.vi[key] ?? key;
  if (params) text = text.replace(/\{(\w+)\}/g, (_match, name) => params[name] ?? `{${name}}`);
  return text;
}
// Source labels remain stable keys; values resolve on access, not at module import.
export function localized<T extends object>(source: T): T {
  return new Proxy(source, {get(target, key, receiver) {
    const value = Reflect.get(target, key, receiver);
    return typeof value === "string" ? tr(value) : value && typeof value === "object" ? localized(value) : value;
  }});
}
